#!/usr/bin/env python3
"""Build identical, integer-aligned app glyphs for the LCD and Animation Lab."""
import argparse
import json
import math
import re
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SIZE = 56
PALETTE = ["#000000", "#ea4335", "#fbbc05", "#34a853", "#4285f4",
           "#f5f8ff", "#1ed760", "#111820", "#5865f2"]


def build_icons():
    icons = {}
    # Three color sectors and a blue center keep Chrome recognizable at 56 pixels.
    image = Image.new("P", (SIZE, SIZE))
    for y in range(SIZE):
        for x in range(SIZE):
            dx, dy = x - 27.5, y - 27.5
            if dx * dx + dy * dy <= 26 * 26:
                angle = (math.degrees(math.atan2(dy, dx)) + 150) % 360
                image.putpixel((x, y), [1, 2, 3][int(angle // 120)])
    draw = ImageDraw.Draw(image)
    draw.ellipse((15, 15, 40, 40), fill=5)
    draw.ellipse((18, 18, 37, 37), fill=4)
    icons["launch_chrome"] = image
    image = Image.new("P", (SIZE, SIZE))
    draw = ImageDraw.Draw(image)
    draw.ellipse((2, 2, 53, 53), fill=6)
    # Curves shrink toward the bottom and rise in the center like sound waves.
    for y, half, width in [(20, 17, 4), (29, 14, 4), (38, 11, 3)]:
        points = [(round(27.5 + half * t / 24),
                   round(y + 4 * (t / 24) ** 2 + 1.3 * t / 24)) for t in range(-24, 25)]
        draw.line(points, fill=7, width=width)
        for x, py in (points[0], points[-1]):
            draw.ellipse((x - width//2, py - width//2, x + width//2, py + width//2), fill=7)
    icons["launch_spotify"] = image
    image = Image.new("P", (SIZE, SIZE))
    draw = ImageDraw.Draw(image)
    # Symmetric Clyde silhouette with sloped shoulders and lower grips.
    draw.polygon([(12,13),(20,10),(22,14),(33,14),(35,10),(43,13),
                  (48,23),(51,37),(42,43),(36,40),(38,36),(17,36),
                  (19,40),(13,43),(4,37),(7,23)], fill=8)
    draw.ellipse((9,16,46,38), fill=8)
    draw.ellipse((16,24,22,32), fill=5)
    draw.ellipse((33,24,39,32), fill=5)
    icons["launch_discord"] = image
    result = {}
    for name, image in icons.items():
        spans = []
        for y in range(SIZE):
            x = 0
            while x < SIZE:
                color = image.getpixel((x,y))
                start = x
                while x < SIZE and image.getpixel((x,y)) == color:
                    x += 1
                if color:
                    spans.append([start,y,x-start,color])
        result[name] = {"label":name.removeprefix("launch_").upper(), "spans":spans}
    return result


def outputs():
    icons = build_icons()
    data = {"size":SIZE, "palette":PALETTE, "icons":icons}
    js = "// BEGIN GENERATED APP ICONS\nconst APP_ICONS=" + json.dumps(data,separators=(",",":")) + ";\n// END GENERATED APP ICONS"
    preview = ROOT / "display-preview.html"
    source = preview.read_text()
    if "// BEGIN GENERATED APP ICONS" in source:
        source = re.sub(r"// BEGIN GENERATED APP ICONS[\s\S]*?// END GENERATED APP ICONS",
                        lambda _:js, source)
    else:
        source = source.replace("<script>", "<script>\n"+js, 1)
    header = ['// Generated by tools/generate_app_icons.py.\n#pragma once\n',
              'struct AppIconSpan { uint8_t x, y, width, color; };\n']
    colors = [int(c[1:3],16) >> 3 << 11 | int(c[3:5],16) >> 2 << 5 | int(c[5:7],16) >> 3 for c in PALETTE]
    header.append('const uint16_t APP_ICON_PALETTE[] = {'+','.join(map(str,colors))+'};\n')
    for name, info in icons.items():
        header.append('const AppIconSpan ICON_'+name.upper()+'[] PROGMEM = {\n')
        header.extend('  {'+','.join(map(str,row))+'},\n' for row in info["spans"])
        header.append('};\n')
    return {preview:source, ROOT/"firmware/include/app_icons.h":''.join(header)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check",action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text()!=content:
                raise SystemExit(f"Regenerate app icons: {path}")
        else:
            path.write_text(content)
